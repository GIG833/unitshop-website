-- UNITSHOP display-only homepage promotions. No checkout/price/order integration.
-- Creating the table does not publish any offer; each entry defaults inactive.
create table if not exists public.promotions (
  id bigint generated by default as identity primary key,
  title_en text not null check (length(btrim(title_en)) between 1 and 120),
  title_mm text check (title_mm is null or length(title_mm) <= 120),
  body_en text check (body_en is null or length(body_en) <= 320),
  body_mm text check (body_mm is null or length(body_mm) <= 320),
  image_url text check (image_url is null or (length(image_url) <= 2048 and image_url like 'https://%')),
  sort_order integer not null default 0 check (sort_order between 0 and 1000),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.promotions enable row level security;

-- Only enabled offers are visible to guests; admins may see inactive drafts.
revoke all on table public.promotions from public, anon, authenticated;
grant select on table public.promotions to anon;
grant select, insert, update, delete on table public.promotions to authenticated;
grant usage, select on sequence public.promotions_id_seq to authenticated;

create policy "Public can view enabled promotions"
on public.promotions for select to anon, authenticated
using (is_active = true);

create policy "Admins can view all promotions"
on public.promotions for select to authenticated
using ((select public.is_admin()));

create policy "Admins can create promotions"
on public.promotions for insert to authenticated
with check ((select public.is_admin()));

create policy "Admins can edit promotions"
on public.promotions for update to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "Admins can remove promotions"
on public.promotions for delete to authenticated
using ((select public.is_admin()));
